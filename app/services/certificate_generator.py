from pathlib import Path
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

BASE_DIR = Path(__file__).resolve().parents[2]
OUTPUT_DIR = BASE_DIR / "generated"
OUTPUT_DIR.mkdir(exist_ok=True)


def safe_filename(name: str) -> str:
    cleaned = "".join(c if c.isalnum() or c in " _-" else "_" for c in name)
    return "_".join(cleaned.split())


def generate_certificate(
    recipient_name: str,
    event_name: str,
    event_date: str,
    certificate_id: int,
) -> str:
    filename = f"certificate_{certificate_id}_{safe_filename(recipient_name)}.pdf"
    output_path = OUTPUT_DIR / filename

    c = canvas.Canvas(str(output_path), pagesize=A4)
    width, height = A4

    # Single predefined certificate design.
    c.setTitle(f"Certificate - {recipient_name}")
    c.setLineWidth(3)
    c.rect(40, 40, width - 80, height - 80)

    c.setFont("Helvetica-Bold", 28)
    c.drawCentredString(width / 2, height - 150, "CERTIFICATE OF PARTICIPATION")

    c.setFont("Helvetica", 16)
    c.drawCentredString(width / 2, height - 210, "This certificate is proudly presented to")

    c.setFont("Helvetica-Bold", 25)
    c.drawCentredString(width / 2, height - 270, recipient_name)

    c.setFont("Helvetica", 15)
    c.drawCentredString(
        width / 2,
        height - 330,
        f"for successfully participating in {event_name}",
    )

    c.setFont("Helvetica", 13)
    c.drawCentredString(width / 2, height - 370, f"Event Date: {event_date}")

    c.setFont("Helvetica", 10)
    c.drawCentredString(width / 2, 80, "Generated by Bulk Certificate Generator API")

    c.save()
    return str(output_path)
